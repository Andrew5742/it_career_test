  async function createPdfBlob() {
    const node = resultPdfRef.current;
    if (!node) return null;

    const previousStyle = node.getAttribute("style") ?? "";

    node.style.width = "794px";
    node.style.height = "1123px";
    node.style.minHeight = "1123px";
    node.style.maxHeight = "1123px";
    node.style.overflow = "hidden";
    node.style.transform = "none";

    try {
      if (document.fonts?.ready) {
        await document.fonts.ready;
      }

      const canvas = await html2canvas(node, {
        scale: 2,
        width: 794,
        height: 1123,
        windowWidth: 794,
        windowHeight: 1123,
        scrollX: 0,
        scrollY: 0,
        backgroundColor: "#ffffff",
        useCORS: true,
        logging: false,
      });

      const image = canvas.toDataURL("image/png", 1);
      const pdf = new jsPDF({
        orientation: "portrait",
        unit: "mm",
        format: "a4",
        compress: true,
      });

      pdf.addImage(image, "PNG", 0, 0, 210, 297);
      pdf.link(24, 261, 74, 7, { url: "https://kiis.khmnu.edu.ua/" });
      pdf.link(24, 272, 100, 7, { url: "https://kiis.khmnu.edu.ua/abiturientu/" });

      return pdf.output("blob");
    } finally {
      node.setAttribute("style", previousStyle);
    }
  }

  async function shareResult() {
    const text = getShareText();
    const pdfBlob = await createPdfBlob();
    const files = pdfBlob ? [new File([pdfBlob], "my-it-profile.pdf", { type: "application/pdf" })] : [];

    try {
      if (navigator.share && files.length > 0 && navigator.canShare?.({ files })) {
        await navigator.share({ title: "Мій ІТ-профіль", text, files });
        return;
      }

      if (navigator.share) {
        await navigator.share({ title: "Мій ІТ-профіль", text });
        return;
      }

      await navigator.clipboard.writeText(text);
      alert("Результат скопійовано. PDF можна завантажити окремою кнопкою нижче.");
    } catch (error) {
      console.error(error);
      alert("Не вдалося відкрити поширення. Спробуй кнопку завантаження PDF.");
    }
  }

  async function downloadPdf() {
    const pdfBlob = await createPdfBlob();
    if (!pdfBlob) return;

    const file = new File([pdfBlob], "my-it-profile.pdf", { type: "application/pdf" });

    try {
      // На iPhone/iPad браузер часто не дає примусово завантажити blob-файл.
      // Через share sheet користувач може одразу зберегти PDF у Files або надіслати його.
      if (navigator.share && navigator.canShare?.({ files: [file] })) {
        await navigator.share({ title: "Мій ІТ-профіль PDF", files: [file] });
        return;
      }
    } catch (error) {
      console.error(error);
    }

    const url = URL.createObjectURL(pdfBlob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "my-it-profile.pdf";
    link.rel = "noopener";
    document.body.appendChild(link);
    link.click();
    link.remove();

    setTimeout(() => URL.revokeObjectURL(url), 5000);
  }

