function seededRandom(seed: number) {
  let value = seed % 2147483647;

  if (value <= 0) {
    value += 2147483646;
  }

  return () => {
    value = (value * 16807) % 2147483647;
    return (value - 1) / 2147483646;
  };
}

function shuffleWithSeed<T>(array: T[], seed: number): T[] {
  const random = seededRandom(seed);
  const result = [...array];

  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }

  return result;
}

// Питання та відповіді перемішуються стабільно для конкретного QR-сеансу.
function getQuestions(difficulty: Difficulty, count: number, seed: number) {
  const allowedQuestions = allQuestions.filter((item) => item.difficulty === difficulty);

  const shuffledQuestions = shuffleWithSeed(allowedQuestions, seed).slice(
    0,
    Math.min(count, allowedQuestions.length)
  );

  return shuffledQuestions.map((question, questionIndex) => {
    return {
      ...question,
      answers: shuffleWithSeed(question.answers, seed + question.id + questionIndex + 1000),
    };
  });
}

